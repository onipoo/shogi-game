// 現在の局面に対する定跡手を返す（合致しなければ null）
function getBookMove() {
  const key = kifuLog.join(',');
  const bookEntry = OPENING_BOOK.get(key);
  if (!bookEntry) return null;

  // 実際に合法手かどうか確認してから返す（安全チェック）
  const legal = getLegalMoves('white');
  return legal.find(m =>
    m.drop === bookEntry.drop &&
    m.piece === bookEntry.piece &&
    m.to.row === bookEntry.to.row &&
    m.to.col === bookEntry.to.col &&
    (bookEntry.from == null ||
      (m.from && m.from.row === bookEntry.from.row && m.from.col === bookEntry.from.col))
  ) || null;
}
